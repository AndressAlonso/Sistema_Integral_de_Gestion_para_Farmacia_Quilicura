import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import PromotionsPage from './PromotionsPage'
import { listPromotions, savePromotion } from './promotions.api'
import { listCategories, listProducts } from '../catalog.api'

vi.mock('./promotions.api', () => ({ listPromotions: vi.fn(), savePromotion: vi.fn() }))
vi.mock('../catalog.api', () => ({ listProducts: vi.fn(), listCategories: vi.fn() }))
const product = { id: 'product', name: 'Producto de prueba', sku: 'QA', is_active: true, category_id: 'category', price: '1000', description: '', requires_prescription: false, published_online: true, barcodes: [], image_url: null }
const promotion = { id: 'promotion', name: 'Oferta de prueba', kind: 'PERCENT' as const, value: '20', starts_at: '2026-10-12T12:00:00Z', ends_at: '2026-10-13T12:00:00Z', product_id: 'product', category_id: null, is_active: true, created_at: '2026-10-12T12:00:00Z' }
const originalShow = Object.getOwnPropertyDescriptor(HTMLDialogElement.prototype, 'showModal')
const originalClose = Object.getOwnPropertyDescriptor(HTMLDialogElement.prototype, 'close')
afterEach(() => {
  cleanup()
  if (originalShow) Object.defineProperty(HTMLDialogElement.prototype, 'showModal', originalShow)
  else Reflect.deleteProperty(HTMLDialogElement.prototype, 'showModal')
  if (originalClose) Object.defineProperty(HTMLDialogElement.prototype, 'close', originalClose)
  else Reflect.deleteProperty(HTMLDialogElement.prototype, 'close')
})
beforeEach(() => {
  vi.resetAllMocks()
  Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value: function (this: HTMLDialogElement) { this.setAttribute('open', '') } })
  Object.defineProperty(HTMLDialogElement.prototype, 'close', { configurable: true, value: function (this: HTMLDialogElement) { this.removeAttribute('open') } })
  vi.mocked(listPromotions).mockResolvedValue([])
  vi.mocked(listProducts).mockResolvedValue([product])
  vi.mocked(listCategories).mockResolvedValue([{ id: 'category', name: 'Categoría de prueba' }])
  vi.mocked(savePromotion).mockResolvedValue(promotion)
})
describe('E2-H3', () => {
  it('muestra carga, lista vacía y la regla sin acumular descuentos', async () => {
    render(<PromotionsPage />)
    expect(screen.getByRole('status').textContent).toContain('Cargando')
    expect(await screen.findByText('No hay promociones registradas.')).toBeTruthy()
    expect(screen.getByText(/Los descuentos no se acumulan/)).toBeTruthy()
  })
  it('guarda una promoción con destino exclusivo y fechas con zona horaria', async () => {
    render(<PromotionsPage />)
    await screen.findByText('No hay promociones registradas.')
    fireEvent.click(screen.getByRole('button', { name: 'Nueva promoción' }))
    fireEvent.change(screen.getByLabelText('Nombre'), { target: { value: 'Oferta de prueba' } })
    fireEvent.change(screen.getByLabelText('Porcentaje (%)'), { target: { value: '20' } })
    fireEvent.change(screen.getByLabelText('Producto'), { target: { value: 'product' } })
    fireEvent.change(screen.getByLabelText('Inicio (hora local)'), { target: { value: '2026-10-12T12:00' } })
    fireEvent.change(screen.getByLabelText('Término (hora local)'), { target: { value: '2026-10-13T12:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Confirmar promoción' }))
    await waitFor(() => expect(savePromotion).toHaveBeenCalledTimes(1))
    expect(vi.mocked(savePromotion).mock.calls[0][0]).toMatchObject({ product_id: 'product', category_id: null, value: '20' })
    expect(vi.mocked(savePromotion).mock.calls[0][0].starts_at).toMatch(/Z$/)
    expect(await screen.findByText('Oferta de prueba')).toBeTruthy()
  })
  it('permite editar y desactivar sin borrar el registro', async () => {
    vi.mocked(listPromotions).mockResolvedValue([promotion])
    render(<PromotionsPage />)
    fireEvent.click(await screen.findByRole('button', { name: 'Editar' }))
    fireEvent.click(screen.getByLabelText('Habilitada'))
    fireEvent.click(screen.getByRole('button', { name: 'Confirmar promoción' }))
    await waitFor(() => expect(savePromotion).toHaveBeenCalledTimes(1))
    expect(vi.mocked(savePromotion).mock.calls[0][0].is_active).toBe(false)
    expect(vi.mocked(savePromotion).mock.calls[0][1]).toBe('promotion')
  })
  it('permite aplicar a una categoría sin seleccionar ni disponer de productos', async () => {
    vi.mocked(listProducts).mockResolvedValue([])
    vi.mocked(savePromotion).mockResolvedValue({ ...promotion, product_id: null, category_id: 'category' })
    render(<PromotionsPage />)
    await screen.findByText('No hay promociones registradas.')
    fireEvent.click(screen.getByRole('button', { name: 'Nueva promoción' }))
    fireEvent.change(screen.getByLabelText('Aplicar a'), { target: { value: 'category' } })
    expect(screen.queryByLabelText('Producto')).toBeNull()
    expect(screen.getByText(/No necesitas seleccionar un producto/)).toBeTruthy()
    fireEvent.change(screen.getByLabelText('Nombre'), { target: { value: 'Oferta de categoría' } })
    fireEvent.change(screen.getByLabelText('Porcentaje (%)'), { target: { value: '10' } })
    fireEvent.change(screen.getByLabelText('Categoría'), { target: { value: 'category' } })
    fireEvent.change(screen.getByLabelText('Inicio (hora local)'), { target: { value: '2026-10-12T12:00' } })
    fireEvent.change(screen.getByLabelText('Término (hora local)'), { target: { value: '2026-10-13T12:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Confirmar promoción' }))
    await waitFor(() => expect(savePromotion).toHaveBeenCalledTimes(1))
    expect(vi.mocked(savePromotion).mock.calls[0][0]).toMatchObject({ category_id: 'category', product_id: null })
  })
  it.each(['product', 'category'])('limpia la selección al cambiar desde %s y exige solo el nuevo destino', async target => {
    render(<PromotionsPage />)
    await screen.findByText('No hay promociones registradas.')
    fireEvent.click(screen.getByRole('button', { name: 'Nueva promoción' }))
    fireEvent.change(screen.getByLabelText('Aplicar a'), { target: { value: target } })
    const previousLabel = target === 'product' ? 'Producto' : 'Categoría'
    fireEvent.change(screen.getByLabelText(previousLabel), { target: { value: target } })
    const next = target === 'product' ? 'category' : 'product'
    fireEvent.change(screen.getByLabelText('Aplicar a'), { target: { value: next } })
    expect(screen.queryByLabelText(previousLabel)).toBeNull()
    const selected = screen.getByLabelText(next === 'product' ? 'Producto' : 'Categoría') as HTMLSelectElement
    expect(selected.value).toBe('')
    expect(selected.required).toBe(true)
  })
  it('permite aplicar a un producto sin disponer de categorías', async () => {
    vi.mocked(listCategories).mockResolvedValue([])
    render(<PromotionsPage />)
    await screen.findByText('No hay promociones registradas.')
    fireEvent.click(screen.getByRole('button', { name: 'Nueva promoción' }))
    expect(screen.queryByLabelText('Categoría')).toBeNull()
    fireEvent.change(screen.getByLabelText('Nombre'), { target: { value: 'Oferta de producto' } })
    fireEvent.change(screen.getByLabelText('Porcentaje (%)'), { target: { value: '10' } })
    fireEvent.change(screen.getByLabelText('Producto'), { target: { value: 'product' } })
    fireEvent.change(screen.getByLabelText('Inicio (hora local)'), { target: { value: '2026-10-12T12:00' } })
    fireEvent.change(screen.getByLabelText('Término (hora local)'), { target: { value: '2026-10-13T12:00' } })
    fireEvent.click(screen.getByRole('button', { name: 'Confirmar promoción' }))
    await waitFor(() => expect(savePromotion).toHaveBeenCalledTimes(1))
    expect(vi.mocked(savePromotion).mock.calls[0][0]).toMatchObject({ product_id: 'product', category_id: null })
  })
  it('muestra errores de carga sin inventar promociones', async () => {
    vi.mocked(listPromotions).mockRejectedValue(new Error('No disponible'))
    render(<PromotionsPage />)
    expect((await screen.findByRole('alert')).textContent).toContain('No disponible')
  })
})

it('abre un formulario nuevo solo al solicitarlo y cancelar no guarda datos', async () => {
  render(<PromotionsPage />)
  await screen.findByText('No hay promociones registradas.')
  expect(screen.queryByRole('dialog')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Nueva promoción' }))
  expect(screen.getByRole('dialog', { name: 'Crear promoción' })).toBeTruthy()
  fireEvent.change(screen.getByLabelText('Nombre'), { target: { value: 'Borrador sin guardar' } })
  fireEvent.click(screen.getByRole('button', { name: 'Cancelar' }))
  expect(screen.queryByRole('dialog')).toBeNull()
  expect(savePromotion).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Nueva promoción' }))
  expect((screen.getByLabelText('Nombre') as HTMLInputElement).value).toBe('')
})
